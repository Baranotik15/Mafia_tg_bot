class Command(BaseCommand):
    help = 'Seed database with 30 unique cards'

    def handle(self, *args, **options):
        created = 0
        for slug, name, rarity, desc in CARDS:
            _, was_created = Card.objects.update_or_create(
                slug=slug,
                defaults={'name': name, 'rarity': rarity, 'description': desc},
            )
            if was_created:
                created += 1
        self.stdout.write(self.style.SUCCESS(
            f'Done. Created {created}, total {Card.objects.count()} cards.'
        ))
